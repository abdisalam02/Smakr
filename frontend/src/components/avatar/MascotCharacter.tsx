/**
 * Smakr Mascot System — production avatar pipeline.
 *
 * The base character is generated by DiceBear (`@dicebear/core`) with either
 * the **Open Peeps** or **Micah** vector engine. We never hand-draw the
 * anatomy: DiceBear owns the skull, hair bounds, facial features and hands,
 * which permanently eliminates claw fingers and floating-hair artefacts.
 *
 * Colour channels are mapped 1:1 to independent engine colour slots so that
 * changing one swatch can never recolour another. A curated, self-contained
 * food-prop overlay is composed beside the avatar — no finger geometry.
 */

export const MASCOT_VIEWBOX_WIDTH = 320;
export const MASCOT_VIEWBOX_HEIGHT = 280;

