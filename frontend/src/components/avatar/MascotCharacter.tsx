function propLayer(prop: MascotFoodProp, colors: PropColors, motion: boolean): string {
  const inner = propMarkup(prop, colors, motion);
  if (!inner) return "";
  return `<g data-layer="prop" transform="translate(${PROP_ORIGIN.x} ${PROP_ORIGIN.y})">${inner}</g>`;
}

/* ------------------------------------------------------------------ */
/* Ambience — ground shadow + optional radar beacon                    */
/* ------------------------------------------------------------------ */

function ambienceLayer(config: MascotConfig, motion: boolean, colors: PropColors): string {
  const beacon = config.showBeacon
    ? `
      <ellipse cx="${GROUND.cx}" cy="${GROUND.cy}" rx="70" ry="21" fill="none" stroke="${colors.ribbon}" stroke-width="4"${motion ? ' class="mascot-ping"' : ' opacity="0.55"'} />
      ${
        motion
          ? `<ellipse cx="${GROUND.cx}" cy="${GROUND.cy}" rx="70" ry="21" fill="none" stroke="${colors.ribbon}" stroke-width="3" class="mascot-ping mascot-ping-delay" />`
          : ""
      }
    `
    : "";

  return `
    <g data-layer="ambience">
      <ellipse cx="${GROUND.cx}" cy="${GROUND.cy}" rx="52" ry="12" fill="${INK}" opacity="0.16" />
      ${beacon}
    </g>
  `;
}

/* ------------------------------------------------------------------ */
/* Assembler                                                           */
/* ------------------------------------------------------------------ */

export function buildMascotBody(
  config: MascotConfig = DEFAULT_MASCOT_CONFIG,
  animated = false
): string {
  const motion = animated && config.animation !== "static";
  const motionClass = !motion
    ? ""
    : config.animation === "cheerful-bounce"
    ? "mascot-bounce"
    : "mascot-float";

  const colors: PropColors = {
    accent: toHex(config.accessoryColor, "1b3bce"),
    ribbon: toHex(config.hatColor, "e84a27"),
    base: toHex(config.bottomColor, "1f2937"),
  };

  const avatar = parseAvatar(renderEngineAvatar(config));
  const scale = Math.min(AVATAR_BOX.w / avatar.vbW, AVATAR_BOX.h / avatar.vbH);
  const tx = AVATAR_BOX.x + (AVATAR_BOX.w - avatar.vbW * scale) / 2 - avatar.minX * scale;
  const ty = AVATAR_BOX.y + (AVATAR_BOX.h - avatar.vbH * scale) / 2 - avatar.minY * scale;

  return [
    ambienceLayer(config, motion, colors),
    `<g class="${motionClass}">`,
    `<g data-layer="avatar" data-engine="${config.engine}" transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${scale.toFixed(4)})">${avatar.body}</g>`,
    propLayer(config.prop, colors, motion),
    `</g>`,
  ].join("\n");
}

/** Builds a standalone, self-contained <svg> string with explicit dimensions. */
export function buildMascotSVGString(
  config: MascotConfig = DEFAULT_MASCOT_CONFIG,
  animated = false,
  width = MASCOT_VIEWBOX_WIDTH,
  height = Math.round((width * MASCOT_VIEWBOX_HEIGHT) / MASCOT_VIEWBOX_WIDTH)
): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${width}" height="${height}" fill="none" style="overflow:visible;display:block;">${buildMascotBody(
    config,
    animated
  )}</svg>`;
}

