/* Compose geometry                                                    */
/* ------------------------------------------------------------------ */

const CANVAS = { w: MASCOT_VIEWBOX_WIDTH, h: MASCOT_VIEWBOX_HEIGHT };
const AVATAR_BOX = { x: 4, y: 2, w: 232, h: 256 };
const PROP_ORIGIN = { x: 268, y: 186 };
const GROUND = { cx: AVATAR_BOX.x + AVATAR_BOX.w / 2, cy: 262 };

const INK = "#241c16";
