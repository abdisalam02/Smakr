interface MascotCharacterProps {
  config?: Partial<MascotConfig>;
  size?: number;
  className?: string;
  animated?: boolean;
}

/**
 * Module-level memo cache for generated mascot SVGs. DiceBear's `createAvatar`
 * runs synchronously and is CPU-heavy; without this, every store update
 * (hydrating venues/posts/user) regenerated every mascot on screen and blocked
 * the main thread, delaying first paint of live data.
 */
const mascotSvgCache = new Map<string, string>();

function buildMascotSvgCached(
  config: MascotConfig,
  animated: boolean,
  size: number,
  height: number
): string {
  const key = `${size}x${height}|${animated ? "a" : "s"}|${JSON.stringify(config)}`;
  const cached = mascotSvgCache.get(key);
  if (cached) return cached;
  const svg = buildMascotSVGString(config, animated, size, height);
  if (mascotSvgCache.size >= 100) mascotSvgCache.clear();
  mascotSvgCache.set(key, svg);
  return svg;
}

export const MascotCharacter = React.memo(function MascotCharacter({
  config,
  size = 120,
  className = "",
  animated = false,
}: MascotCharacterProps) {
  const merged: MascotConfig = { ...DEFAULT_MASCOT_CONFIG, ...config };
  const height = Math.round((size * MASCOT_VIEWBOX_HEIGHT) / MASCOT_VIEWBOX_WIDTH);

  const svg = React.useMemo(
    () => buildMascotSvgCached(merged, animated, size, height),
    // `merged` is a fresh object each render — key the memo on its JSON content.
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [JSON.stringify(merged), animated, size, height]
  );

  return (
    <span
      className={className}
      style={{
        display: "inline-block",
        width: size,
        height,
        lineHeight: 0,
        verticalAlign: "middle",
      }}
      role="img"
      aria-label="Smakr mascot"
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
});

/* ------------------------------------------------------------------ */
/* MapLibre GL DOM marker generator                                    */
/* ------------------------------------------------------------------ */

export function createMascotDOMElement(config: MascotConfig, width = 38): HTMLDivElement {
  const merged: MascotConfig = { ...DEFAULT_MASCOT_CONFIG, ...config };

  const height = Math.round((width * MASCOT_VIEWBOX_HEIGHT) / MASCOT_VIEWBOX_WIDTH);

  const root = document.createElement("div");
  root.className = "maplibregl-marker smakr-mascot-marker";
  root.style.position = "absolute";
  root.style.top = "0";
  root.style.left = "0";
  root.style.width = `${width}px`;
  root.style.height = `${height}px`;
  root.style.cursor = "default";
  root.style.userSelect = "none";
  root.style.zIndex = "50";
  root.style.pointerEvents = "none";

  root.innerHTML = buildMascotSVGString(merged, true, width, height);
  return root;
}
