/* ------------------------------------------------------------------ */
/* Value normalisation (guards stale localStorage / free-form input)   */
/* ------------------------------------------------------------------ */

const HEX_RE = /^[0-9a-fA-F]{6}$/;

function normalizeHex(value: unknown, fallback: string): string {
  const raw = typeof value === "string" ? value.replace(/^#/, "").trim() : "";
  return HEX_RE.test(raw) ? raw.toLowerCase() : fallback;
}

function toHex(value: unknown, fallback: string): string {
  return `#${normalizeHex(value, fallback)}`;
}

function pickValid(value: unknown, allowed: readonly string[], fallback: string): string {
  return typeof value === "string" && allowed.includes(value) ? value : fallback;
}

const ids = (options: { id: string }[]): string[] => options.map((o) => o.id);

const PEEPS_HEAD_VALUES = ids(PEEPS_HEAD_OPTIONS);
const PEEPS_FACE_VALUES = ids(PEEPS_FACE_OPTIONS);
const PEEPS_FACIAL_HAIR_VALUES = ids(PEEPS_FACIAL_HAIR_OPTIONS);
const PEEPS_ACCESSORY_VALUES = ids(PEEPS_ACCESSORY_OPTIONS);
const MICAH_HAIR_VALUES = ids(MICAH_HAIR_OPTIONS);
const MICAH_EYES_VALUES = ids(MICAH_EYES_OPTIONS);
const MICAH_EYEBROW_VALUES = ids(MICAH_EYEBROW_OPTIONS);
const MICAH_MOUTH_VALUES = ids(MICAH_MOUTH_OPTIONS);
const MICAH_EARS_VALUES = ids(MICAH_EARS_OPTIONS);
const MICAH_GLASSES_VALUES = ids(MICAH_GLASSES_OPTIONS);
const MICAH_SHIRT_VALUES = ids(MICAH_SHIRT_OPTIONS);

type PeepsHead = NonNullable<PeepsOptions["head"]>[number];
type PeepsFace = NonNullable<PeepsOptions["face"]>[number];
type PeepsFacialHair = NonNullable<PeepsOptions["facialHair"]>[number];
type PeepsAccessory = NonNullable<PeepsOptions["accessories"]>[number];
type MicahHair = NonNullable<MicahOptions["hair"]>[number];
type MicahEyes = NonNullable<MicahOptions["eyes"]>[number];
type MicahEyebrow = NonNullable<MicahOptions["eyebrows"]>[number];
type MicahMouth = NonNullable<MicahOptions["mouth"]>[number];
type MicahEar = NonNullable<MicahOptions["ears"]>[number];
type MicahGlasses = NonNullable<MicahOptions["glasses"]>[number];
type MicahShirt = NonNullable<MicahOptions["shirt"]>[number];

/* ------------------------------------------------------------------ */
/* Engine option builders — one independent channel per colour         */
/* ------------------------------------------------------------------ */

function peepsOptions(config: MascotConfig): StyleOptions<PeepsOptions> {
  const head = pickValid(config.peepsHead, PEEPS_HEAD_VALUES, DEFAULT_MASCOT_CONFIG.peepsHead);
  const face = pickValid(config.peepsFace, PEEPS_FACE_VALUES, DEFAULT_MASCOT_CONFIG.peepsFace);
  const facialHair = config.peepsFacialHair && config.peepsFacialHair !== "none"
    ? pickValid(config.peepsFacialHair, PEEPS_FACIAL_HAIR_VALUES, "chin")
    : null;
  const accessories = config.peepsAccessories && config.peepsAccessories !== "none"
    ? pickValid(config.peepsAccessories, PEEPS_ACCESSORY_VALUES, "glasses")
    : null;

  return {
    seed: config.seed,
    head: [head as PeepsHead],
    face: [face as PeepsFace],
    facialHair: facialHair ? [facialHair as PeepsFacialHair] : [],
    facialHairProbability: facialHair ? 100 : 0,
    mask: [],
    maskProbability: 0,
    accessories: accessories ? [accessories as PeepsAccessory] : [],
    accessoriesProbability: accessories ? 100 : 0,
    // Independent colour channels ↓ (skin · hair · clothing)
    skinColor: [normalizeHex(config.skinColor, "ffdfbf")],
    headContrastColor: [normalizeHex(config.hairColor, "241c16")],
    clothingColor: [normalizeHex(config.topColor, "3d5a45")],
  };
}

function micahOptions(config: MascotConfig): StyleOptions<MicahOptions> {
  const hair = pickValid(config.micahHair, MICAH_HAIR_VALUES, DEFAULT_MASCOT_CONFIG.micahHair);
  const eyes = pickValid(config.micahEyes, MICAH_EYES_VALUES, DEFAULT_MASCOT_CONFIG.micahEyes);
  const eyebrows = pickValid(config.micahEyebrows, MICAH_EYEBROW_VALUES, DEFAULT_MASCOT_CONFIG.micahEyebrows);
  const mouth = pickValid(config.micahMouth, MICAH_MOUTH_VALUES, DEFAULT_MASCOT_CONFIG.micahMouth);
  const ears = pickValid(config.micahEars, MICAH_EARS_VALUES, DEFAULT_MASCOT_CONFIG.micahEars);
  const shirt = pickValid(config.micahShirt, MICAH_SHIRT_VALUES, DEFAULT_MASCOT_CONFIG.micahShirt);
  const glasses = config.micahGlasses && config.micahGlasses !== "none"
    ? pickValid(config.micahGlasses, MICAH_GLASSES_VALUES, "round")
    : null;
  const hairHex = normalizeHex(config.hairColor, "241c16");

  return {
    seed: config.seed,
    base: ["standard"],
    hair: [hair as MicahHair],
    hairProbability: 100,
    eyes: [eyes as MicahEyes],
    eyebrows: [eyebrows as MicahEyebrow],
    mouth: [mouth as MicahMouth],
    ears: [ears as MicahEar],
    nose: ["curve"],
    shirt: [shirt as MicahShirt],
    glasses: glasses ? [glasses as MicahGlasses] : [],
    glassesProbability: glasses ? 100 : 0,
    facialHair: [],
    facialHairProbability: 0,
    earrings: [],
    earringsProbability: 0,
    // Independent colour channels ↓ (skin · hair · shirt · accessory)
    baseColor: [normalizeHex(config.skinColor, "f9c9b6")],
    hairColor: [hairHex],
    eyebrowsColor: [hairHex],
    shirtColor: [normalizeHex(config.topColor, "3d5a45")],
    glassesColor: [normalizeHex(config.accessoryColor, "1b3bce")],
    mouthColor: ["241c16"],
    eyesColor: ["241c16"],
  };
}

function renderEngineAvatar(config: MascotConfig): string {
  const result =
    config.engine === "micah"
      ? createAvatar(micah, micahOptions(config))
      : createAvatar(openPeeps, peepsOptions(config));
  return result.toString();
}

/* ------------------------------------------------------------------ */
/* Strip the DiceBear wrapper so we can compose in our own canvas      */
/* ------------------------------------------------------------------ */

interface ParsedAvatar {
  minX: number;
  minY: number;
  vbW: number;
  vbH: number;
  body: string;
}

function parseAvatar(svg: string): ParsedAvatar {
  const match = svg.match(/<svg[^>]*?viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>/);
  const viewBox = match ? match[1] : "0 0 100 100";
  let body = match ? match[2] : svg;
  // Drop license metadata comments emitted by DiceBear.
  body = body.replace(/<!--[\s\S]*?-->/g, "");

  const p = viewBox.trim().split(/[\s,]+/).map(Number);
  return {
    minX: Number.isFinite(p[0]) ? p[0] : 0,
    minY: Number.isFinite(p[1]) ? p[1] : 0,
    vbW: Number.isFinite(p[2]) && p[2] > 0 ? p[2] : 100,
    vbH: Number.isFinite(p[3]) && p[3] > 0 ? p[3] : 100,
    body,
  };
}

